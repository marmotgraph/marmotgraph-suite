package org.marmotgraph.suite.api;

import com.fasterxml.jackson.annotation.JsonInclude;
import lombok.AllArgsConstructor;
import org.marmotgraph.sdk.MarmotGraphApiException;
import org.marmotgraph.sdk.MarmotGraphClient;
import org.marmotgraph.sdk.model.ToolCategory;
import org.marmotgraph.sdk.model.ToolDefinition;
import org.marmotgraph.sdk.model.ToolSpecification;
import org.marmotgraph.suite.auth.AuthenticatedClient;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.server.ResponseStatusException;

import java.nio.charset.StandardCharsets;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Base64;
import java.util.EnumSet;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import java.util.Set;
import java.util.UUID;
import java.util.function.Predicate;
import java.util.stream.IntStream;

/**
 * Exports the settings of the admin sections (the specifications of the spaces - without their types -, the permissions,
 * the tenants and the tools) into a single document - and imports such a document again, e.g. to restore the setup
 * after the database of the core has been wiped. Everything is done on behalf of the user who issued the request with
 * the endpoints of the admin sections - the user therefore needs the same rights as for managing the settings
 * individually.
 * <p>
 * The document doesn't contain any identifiers generated by the core: tool categories are identified by their name and
 * tools by their name too. An import creates or updates the settings - it never removes anything (claims are added to
 * the claims of a role).
 */
@AllArgsConstructor
@RestController
@RequestMapping("/admin/settings")
public class SettingsTransfer {

    /**
     * The value identifying a settings document.
     */
    static final String FORMAT = "marmotgraph-suite-settings";

    /**
     * The version of the document structure - documents of later versions are rejected.
     */
    static final int VERSION = 1;

    public enum Section {spaces, permissions, tenants, tools}

    /**
     * The exported settings - a section is null if it isn't part of the document.
     */
    @JsonInclude(JsonInclude.Include.NON_NULL)
    public record SettingsDocument(String format, Integer version, String exportedAt, List<SpaceSettings> spaces,
                                   List<Permissions.RoleDefinition> permissions, List<TenantSettings> tenants, ToolSettings tools) {
    }

    public record SpaceSettings(String identifier, boolean autoRelease, boolean clientSpace, boolean deferCache) {
    }

    @JsonInclude(JsonInclude.Include.NON_NULL)
    public record TenantSettings(String name, String title, String contactEmail, String copyright, Tenants.Theme theme,
                                 List<TenantImage> images) {
    }

    /**
     * An image of the theme of a tenant.
     *
     * @param darkMode whether the image is the one for the dark mode - null for the favicon (which is the same for both)
     * @param data     the content of the image (base64 encoded)
     */
    @JsonInclude(JsonInclude.Include.NON_NULL)
    public record TenantImage(Tenants.Image image, Boolean darkMode, String contentType, String data) {
    }

    public record ToolSettings(List<CategorySettings> categories, List<ToolSettingsEntry> definitions) {
    }

    @JsonInclude(JsonInclude.Include.NON_NULL)
    public record CategorySettings(String name, String icon) {
    }

    /**
     * @param category the name of the category the tool is listed in
     */
    @JsonInclude(JsonInclude.Include.NON_NULL)
    public record ToolSettingsEntry(String name, String description, String category, String endpoint, Map<String, Object> claims) {
    }

    /**
     * The outcome of the import of a single setting.
     *
     * @param item  describes the setting (e.g. the name of the tenant)
     * @param error the reason why the setting couldn't be imported - null if it was imported
     */
    @JsonInclude(JsonInclude.Include.NON_NULL)
    public record ImportResult(Section section, String item, String error) {
    }

    private final SpaceManagement spaceManagement;
    private final Permissions permissions;
    private final Tenants tenants;
    private final ToolsAdmin toolsAdmin;

    /**
     * Exports the settings of the given sections (all if none are given).
     */
    @GetMapping("/export")
    public SettingsDocument export(@AuthenticatedClient MarmotGraphClient client, @RequestParam(required = false) Set<Section> sections) {
        Set<Section> selected = selected(sections);
        return new SettingsDocument(FORMAT, VERSION, Instant.now().toString(),
                selected.contains(Section.spaces) ? exportSpaces(client) : null,
                selected.contains(Section.permissions) ? permissions.list(client) : null,
                selected.contains(Section.tenants) ? exportTenants(client) : null,
                selected.contains(Section.tools) ? exportTools(client) : null);
    }

    /**
     * Imports the settings of the given sections (all of the document if none are given) - in the order of their
     * dependencies (the spaces before their permissions, the categories before their tools). The import continues if a
     * setting can't be imported - the outcome is reported for each of them.
     */
    @PostMapping("/import")
    public List<ImportResult> importSettings(@AuthenticatedClient MarmotGraphClient client, @RequestParam(required = false) Set<Section> sections,
                                             @RequestBody SettingsDocument document) {
        if (document == null || !FORMAT.equals(document.format())) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "The file is not a MarmotGraph settings export");
        }
        if (document.version() == null || document.version() > VERSION) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST,
                    String.format("The version %s of the settings export is not supported (up to %d)", document.version(), VERSION));
        }
        Set<Section> selected = selected(sections);
        List<ImportResult> results = new ArrayList<>();
        if (selected.contains(Section.tenants) && document.tenants() != null) {
            document.tenants().stream().filter(Objects::nonNull).forEach(tenant -> results.add(run(Section.tenants, tenant.name(),
                    () -> importTenant(client, tenant))));
        }
        if (selected.contains(Section.spaces) && document.spaces() != null) {
            document.spaces().stream().filter(Objects::nonNull).forEach(space -> results.add(run(Section.spaces, space.identifier(),
                    () -> spaceManagement.createOrUpdate(client, space.identifier(),
                            new SpaceManagement.Settings(space.autoRelease(), space.clientSpace(), space.deferCache())))));
        }
        if (selected.contains(Section.permissions) && document.permissions() != null) {
            document.permissions().stream().filter(Objects::nonNull).forEach(definition -> results.add(run(Section.permissions, roleLabel(definition),
                    () -> importRoleDefinition(client, definition))));
        }
        if (selected.contains(Section.tools) && document.tools() != null) {
            importTools(client, document.tools(), results);
        }
        return results;
    }

    private static Set<Section> selected(Set<Section> sections) {
        return sections == null || sections.isEmpty() ? EnumSet.allOf(Section.class) : EnumSet.copyOf(sections);
    }

    /**
     * The spaces with an explicit specification - the others have the default settings anyway.
     */
    private List<SpaceSettings> exportSpaces(MarmotGraphClient client) {
        return spaceManagement.list(client).stream()
                .map(space -> spaceManagement.get(client, space.identifier()))
                .filter(SpaceManagement.SpaceDetails::specified)
                .map(details -> new SpaceSettings(details.identifier(), details.settings().autoRelease(), details.settings().clientSpace(),
                        details.settings().deferCache()))
                .toList();
    }

    /**
     * The tenants which can be modified (not the default one) - with their theme and the images they define.
     */
    private List<TenantSettings> exportTenants(MarmotGraphClient client) {
        return tenants.list(client).stream()
                .filter(name -> !Tenants.DEFAULT_TENANT.equals(name))
                .map(name -> {
                    Tenants.Tenant tenant = tenants.get(client, name);
                    return new TenantSettings(name, tenant.title(), tenant.contactEmail(), tenant.copyright(), tenant.theme(),
                            exportImages(client, name));
                })
                .toList();
    }

    private static List<TenantImage> exportImages(MarmotGraphClient client, String tenant) {
        List<TenantImage> images = new ArrayList<>();
        for (boolean darkMode : new boolean[]{false, true}) {
            client.tenants().getLogo(tenant, darkMode).ifPresent(content -> images.add(image(Tenants.Image.logo, darkMode, content)));
            client.tenants().getBackground(tenant, darkMode).ifPresent(content -> images.add(image(Tenants.Image.background, darkMode, content)));
        }
        client.tenants().getFavicon(tenant).ifPresent(content -> images.add(image(Tenants.Image.favicon, null, content)));
        return images;
    }

    private static TenantImage image(Tenants.Image image, Boolean darkMode, byte[] content) {
        return new TenantImage(image, darkMode, contentType(content), Base64.getEncoder().encodeToString(content));
    }

    private ToolSettings exportTools(MarmotGraphClient client) {
        List<CategorySettings> categories = toolsAdmin.listCategories(client).stream()
                .map(category -> new CategorySettings(category.name(), category.icon())).toList();
        List<ToolSettingsEntry> definitions = toolsAdmin.listDefinitions(client).stream()
                .map(tool -> new ToolSettingsEntry(tool.name(), tool.description(), tool.category() != null ? tool.category().name() : null,
                        tool.endpoint(), tool.claims()))
                .toList();
        return new ToolSettings(categories, definitions);
    }

    private void importTenant(MarmotGraphClient client, TenantSettings tenant) {
        if (Tenants.DEFAULT_TENANT.equals(tenant.name())) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "The default tenant can not be modified");
        }
        tenants.define(client, tenant.name(), new Tenants.TenantDefinition(tenant.title(), tenant.contactEmail(), tenant.copyright()));
        Tenants.Theme theme = tenant.theme();
        if (theme != null) {
            if (theme.font() != null && (theme.font().url() != null || theme.font().fontFamily() != null)) {
                tenants.setFont(client, tenant.name(), theme.font());
            }
            if (completeColors(theme.colors())) {
                tenants.setColors(client, tenant.name(), theme.colors());
            }
            if (theme.customCss() != null) {
                tenants.setCustomCss(client, tenant.name(), theme.customCss());
            }
        }
        if (tenant.images() != null) {
            tenant.images().stream().filter(Objects::nonNull).forEach(image -> importImage(client, tenant.name(), image));
        }
    }

    /**
     * If all colors of the scheme of the core are defined - the core only accepts complete color schemes. Exports of
     * tenants without a color scheme of their own contain the defaults of the core (which are therefore set as well).
     */
    private static boolean completeColors(Map<String, Map<String, String>> colors) {
        return colors != null && Tenants.COLOR_VARIABLES.entrySet().stream().allMatch(group -> {
            Map<String, String> values = colors.get(group.getKey());
            return values != null && group.getValue().keySet().stream().allMatch(color -> values.get(color) != null && !values.get(color).isBlank());
        });
    }

    private static void importImage(MarmotGraphClient client, String tenant, TenantImage image) {
        if (image.image() == null || image.data() == null) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "An image of the tenant is incomplete");
        }
        byte[] content;
        try {
            content = Base64.getDecoder().decode(image.data());
        } catch (IllegalArgumentException e) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, String.format("The %s is not base64 encoded", image.image()));
        }
        String contentType = image.contentType() != null ? image.contentType() : contentType(content);
        String filename = image.image().name() + extension(contentType);
        boolean darkMode = !Boolean.FALSE.equals(image.darkMode());
        switch (image.image()) {
            case logo -> client.tenants().setLogo(tenant, content, filename, contentType, darkMode);
            case background -> client.tenants().setBackground(tenant, content, filename, contentType, darkMode);
            case favicon -> client.tenants().setFavicon(tenant, content, filename, contentType);
        }
    }

    private void importRoleDefinition(MarmotGraphClient client, Permissions.RoleDefinition definition) {
        if (definition.role() == null) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "The role is missing");
        }
        if (definition.claims() == null || definition.claims().isEmpty()) {
            // Nothing to add
            return;
        }
        permissions.update(client, definition.role(), definition.space(), false, definition.claims());
    }

    /**
     * Creates the categories and tools which don't exist yet (identified by their name) and updates the others.
     */
    private void importTools(MarmotGraphClient client, ToolSettings tools, List<ImportResult> results) {
        Map<String, UUID> categoryIds = new HashMap<>();
        List<ToolCategory> existingCategories = toolsAdmin.listCategories(client);
        existingCategories.forEach(category -> categoryIds.putIfAbsent(category.name(), category.id()));
        if (tools.categories() != null) {
            tools.categories().stream().filter(Objects::nonNull).forEach(category -> results.add(run(Section.tools, "Category " + category.name(), () -> {
                ToolsAdmin.CategorySpecification specification = new ToolsAdmin.CategorySpecification(category.name(), category.icon());
                UUID id = categoryIds.get(category.name());
                ToolCategory saved = id != null ? toolsAdmin.updateCategory(client, id, specification)
                        : toolsAdmin.createCategory(client, specification);
                categoryIds.put(category.name(), saved.id());
            })));
        }
        if (tools.definitions() != null) {
            Map<String, UUID> toolIds = new HashMap<>();
            toolsAdmin.listDefinitions(client).forEach(tool -> toolIds.putIfAbsent(tool.name(), tool.id()));
            tools.definitions().stream().filter(Objects::nonNull).forEach(tool -> results.add(run(Section.tools, tool.name(), () -> {
                UUID categoryId = Optional.ofNullable(tool.category()).map(categoryIds::get).orElseThrow(() ->
                        new ResponseStatusException(HttpStatus.BAD_REQUEST, String.format("The category \"%s\" doesn't exist", tool.category())));
                ToolSpecification specification = new ToolSpecification(tool.name(), tool.description(), categoryId, tool.endpoint(),
                        tool.claims() != null ? tool.claims() : ToolSpecification.EVERY_AUTHENTICATED_USER);
                UUID id = toolIds.get(tool.name());
                ToolDefinition saved = id != null ? toolsAdmin.update(client, id, specification) : toolsAdmin.create(client, specification);
                toolIds.put(tool.name(), saved.id());
            })));
        }
    }

    /**
     * Imports a single setting - its failure is reported instead of aborting the import.
     */
    private static ImportResult run(Section section, String item, Runnable importer) {
        try {
            importer.run();
            return new ImportResult(section, item, null);
        } catch (RuntimeException e) {
            return new ImportResult(section, item, errorMessage(e));
        }
    }

    private static String errorMessage(RuntimeException e) {
        if (e instanceof ResponseStatusException responseStatusException) {
            return responseStatusException.getReason();
        }
        if (e instanceof MarmotGraphApiException apiException) {
            return String.format("%s (%d)", apiException.message(), apiException.statusCode());
        }
        return e.getMessage();
    }

    private static String roleLabel(Permissions.RoleDefinition definition) {
        return String.format("%s (%s)", definition.role(), definition.space() != null ? definition.space() : "global");
    }

    /**
     * The core doesn't provide the type of the images of a tenant - it is therefore derived from their content.
     */
    static String contentType(byte[] content) {
        Map<String, Predicate<byte[]>> signatures = new LinkedHashMap<>();
        signatures.put("image/png", c -> startsWith(c, 0x89, 'P', 'N', 'G'));
        signatures.put("image/jpeg", c -> startsWith(c, 0xFF, 0xD8, 0xFF));
        signatures.put("image/gif", c -> startsWith(c, 'G', 'I', 'F', '8'));
        signatures.put("image/x-icon", c -> startsWith(c, 0, 0, 1, 0));
        signatures.put("image/webp", c -> startsWith(c, 'R', 'I', 'F', 'F') && c.length >= 12
                && new String(c, 8, 4, StandardCharsets.US_ASCII).equals("WEBP"));
        signatures.put("image/svg+xml", c -> new String(c, 0, Math.min(c.length, 1024), StandardCharsets.UTF_8).contains("<svg"));
        return signatures.entrySet().stream().filter(s -> s.getValue().test(content)).map(Map.Entry::getKey).findFirst()
                .orElse("application/octet-stream");
    }

    private static boolean startsWith(byte[] content, int... prefix) {
        return content.length >= prefix.length && IntStream.range(0, prefix.length).allMatch(i -> (content[i] & 0xFF) == prefix[i]);
    }

    private static String extension(String contentType) {
        return switch (contentType) {
            case "image/png" -> ".png";
            case "image/jpeg" -> ".jpg";
            case "image/gif" -> ".gif";
            case "image/x-icon", "image/vnd.microsoft.icon" -> ".ico";
            case "image/webp" -> ".webp";
            case "image/svg+xml" -> ".svg";
            default -> "";
        };
    }

}
