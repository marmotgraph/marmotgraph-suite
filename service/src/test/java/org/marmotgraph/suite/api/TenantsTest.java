package org.marmotgraph.suite.api;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.marmotgraph.sdk.MarmotGraphClient;
import org.marmotgraph.sdk.model.JsonLdDocument;
import org.marmotgraph.sdk.resources.TenantsResource;
import org.marmotgraph.suite.auth.AuthenticatedClientResolver;
import org.marmotgraph.suite.configuration.ArgumentResolvers;
import org.mockito.Mockito;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Import;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpMethod;
import org.springframework.http.MediaType;
import org.springframework.mock.web.MockMultipartFile;
import org.springframework.test.context.junit.jupiter.web.SpringJUnitWebConfig;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import org.springframework.web.context.WebApplicationContext;
import org.springframework.web.servlet.config.annotation.EnableWebMvc;

import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyMap;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.multipart;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@SpringJUnitWebConfig(TenantsTest.TestConfig.class)
class TenantsTest {

    /**
     * The stylesheet as generated by the core (see TenantService.getCSS in the core).
     */
    static final String CSS = """
            @import url(http://fonts.googleapis.com/css?family=Roboto:400,100);

             html, body, html * {
                font-family: 'Roboto', sans-serif;
             }


            :root {
              --brand-primary: #414042;
              --brand-seconday: #E67634;
              --brand-tertiary: #B2B1B2;

              --grey-200: #e9ecef;
              --grey-900: #212529;

              --link-hover: #6610f2;
            }


            .custom { color: red; }
            """;

    @EnableWebMvc
    @Import({Tenants.class, ApiExceptionHandler.class, AuthenticatedClientResolver.class, ArgumentResolvers.class})
    static class TestConfig {
        @Bean
        MarmotGraphClient marmotGraphClient() {
            return Mockito.mock(MarmotGraphClient.class);
        }
    }

    @Autowired
    private MarmotGraphClient client;

    private TenantsResource tenants;
    private MockMvc mockMvc;

    @BeforeEach
    void setUp(@Autowired WebApplicationContext context) {
        Mockito.reset(client);
        MarmotGraphClient userClient = Mockito.mock(MarmotGraphClient.class);
        tenants = Mockito.mock(TenantsResource.class);
        when(client.withToken("theToken")).thenReturn(userClient);
        when(userClient.tenants()).thenReturn(tenants);
        mockMvc = MockMvcBuilders.webAppContextSetup(context).build();
    }

    @Test
    void themeIsParsedFromTheStylesheetOfTheCore() {
        Tenants.Theme theme = Tenants.theme(CSS);

        assertEquals("http://fonts.googleapis.com/css?family=Roboto:400,100", theme.font().url());
        assertEquals("'Roboto', sans-serif", theme.font().fontFamily());
        assertEquals("#414042", theme.colors().get("brandColors").get("primary"));
        assertEquals("#E67634", theme.colors().get("brandColors").get("secondary"));
        assertEquals("#212529", theme.colors().get("greys").get("grey900"));
        assertNull(theme.colors().get("greys").get("grey300"));
        assertEquals("#6610f2", theme.colors().get("linkColors").get("hoverColor"));
        assertEquals(".custom { color: red; }", theme.customCss());
    }

    @Test
    void themeWithoutFontImport() {
        Tenants.Theme theme = Tenants.theme("html * {\n font-family: Arial;\n}\n\n:root {\n --brand-primary: #000;\n}\n\n");

        assertNull(theme.font().url());
        assertEquals("Arial", theme.font().fontFamily());
        assertEquals("", theme.customCss());
    }

    @Test
    void listIsProvidedByTheCore() throws Exception {
        when(tenants.list()).thenReturn(List.of("default", "mytenant"));

        mockMvc.perform(get("/admin/tenants").header(HttpHeaders.AUTHORIZATION, "Bearer theToken"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$[1]").value("mytenant"));
    }

    @Test
    void getCombinesTheDefinitionAndTheTheme() throws Exception {
        when(tenants.get("mytenant")).thenReturn(new JsonLdDocument(Map.of("title", "My Tenant", "contactEmail", "info@example.org",
                "copyright", "Me", "idNamespace", "https://example.org/")));
        when(tenants.getCss("mytenant")).thenReturn(CSS);

        mockMvc.perform(get("/admin/tenants/mytenant").header(HttpHeaders.AUTHORIZATION, "Bearer theToken"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.name").value("mytenant"))
                .andExpect(jsonPath("$.title").value("My Tenant"))
                .andExpect(jsonPath("$.idNamespace").value("https://example.org/"))
                .andExpect(jsonPath("$.editable").value(true))
                .andExpect(jsonPath("$.theme.font.fontFamily").value("'Roboto', sans-serif"))
                .andExpect(jsonPath("$.theme.colors.brandColors.secondary").value("#E67634"))
                .andExpect(jsonPath("$.theme.customCss").value(".custom { color: red; }"))
                .andExpect(jsonPath("$.css").value(CSS));
    }

    @Test
    void theDefaultTenantIsNotEditable() throws Exception {
        when(tenants.get("default")).thenReturn(new JsonLdDocument(Map.of("title", "MarmotGraph")));
        when(tenants.getCss("default")).thenReturn(CSS);

        mockMvc.perform(get("/admin/tenants/default").header(HttpHeaders.AUTHORIZATION, "Bearer theToken"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.editable").value(false));
    }

    @Test
    void invalidNamesAreRejected() throws Exception {
        mockMvc.perform(put("/admin/tenants/my.tenant").header(HttpHeaders.AUTHORIZATION, "Bearer theToken")
                        .contentType(MediaType.APPLICATION_JSON).content("{\"title\": \"x\"}"))
                .andExpect(status().isBadRequest());
        verify(tenants, never()).define(anyString(), anyMap());
    }

    @Test
    void defineForwardsTheDefinition() throws Exception {
        mockMvc.perform(put("/admin/tenants/mytenant").header(HttpHeaders.AUTHORIZATION, "Bearer theToken")
                        .contentType(MediaType.APPLICATION_JSON).content("{\"title\": \"My Tenant\", \"contactEmail\": \"info@example.org\"}"))
                .andExpect(status().isOk());

        Map<String, Object> expected = new java.util.LinkedHashMap<>();
        expected.put("title", "My Tenant");
        expected.put("contactEmail", "info@example.org");
        expected.put("copyright", null);
        verify(tenants).define("mytenant", expected);
    }

    @Test
    void incompleteColorsAreRejected() throws Exception {
        mockMvc.perform(put("/admin/tenants/mytenant/theme/colors").header(HttpHeaders.AUTHORIZATION, "Bearer theToken")
                        .contentType(MediaType.APPLICATION_JSON).content("{\"brandColors\": {\"primary\": \"#000\"}}"))
                .andExpect(status().isBadRequest());
        verify(tenants, never()).setColors(anyString(), anyMap());
    }

    @Test
    void customCssIsForwardedAsText() throws Exception {
        mockMvc.perform(put("/admin/tenants/mytenant/theme/customCss").header(HttpHeaders.AUTHORIZATION, "Bearer theToken")
                        .contentType(MediaType.TEXT_PLAIN).content(".a { color: blue; }"))
                .andExpect(status().isOk());
        verify(tenants).setCustomCss("mytenant", ".a { color: blue; }");
    }

    @Test
    void imagesAreUploadedForTheRequestedMode() throws Exception {
        MockMultipartFile file = new MockMultipartFile("file", "logo.svg", "image/svg+xml", "<svg/>".getBytes());

        mockMvc.perform(multipart(HttpMethod.PUT, "/admin/tenants/mytenant/theme/logo").file(file).param("darkMode", "false")
                        .header(HttpHeaders.AUTHORIZATION, "Bearer theToken"))
                .andExpect(status().isOk());

        verify(tenants).setLogo("mytenant", "<svg/>".getBytes(), "logo.svg", "image/svg+xml", false);
        verify(tenants, never()).setBackground(anyString(), any(), anyString(), anyString(), Mockito.anyBoolean());
    }

}
